package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const replaceMarker = "// Generated by scripts/rename: the workspace modules require each other at versions that were only\n" +
	"// ever published under the upstream module path, so each of those versions is pinned to its directory.\n"

var (
	useRe     = regexp.MustCompile(`(?m)^\s*(?:use\s+)?(\./\S+)\s*$`)
	moduleRe2 = regexp.MustCompile(`(?m)^module\s+(\S+)`)
	requireRe = regexp.MustCompile(`(?m)^\s*(?:require\s+)?(\S+)\s+(v\S+)`)
)

// PinWorkspace rewrites the replace block of root/go.work so that every version of a workspace module
// that another workspace module requires resolves to the local directory. Without it the go command
// tries to download those versions under the new module path, which no proxy serves. It returns
// whether the file changed. A tree without go.work is left alone.
func PinWorkspace(root string, dryRun bool) (bool, error) {
	workPath := filepath.Join(root, "go.work")
	raw, err := os.ReadFile(workPath)
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	work := string(raw)
	if i := strings.Index(work, replaceMarker); i >= 0 {
		work = strings.TrimRight(work[:i], "\n") + "\n"
	}

	dirs := map[string]string{} // module path -> directory as written in go.work
	mods := map[string]string{} // directory -> go.mod contents
	for _, m := range useRe.FindAllStringSubmatch(work, -1) {
		data, err := os.ReadFile(filepath.Join(root, m[1], "go.mod"))
		if err != nil {
			return false, err
		}
		name := moduleRe2.FindSubmatch(data)
		if name == nil {
			return false, fmt.Errorf("%s/go.mod has no module line", m[1])
		}
		dirs[string(name[1])] = m[1]
		mods[m[1]] = string(data)
	}

	seen := map[string]bool{}
	var lines []string
	for _, mod := range mods {
		for _, r := range requireRe.FindAllStringSubmatch(mod, -1) {
			dir, ok := dirs[r[1]]
			line := fmt.Sprintf("\t%s %s => %s\n", r[1], r[2], dir)
			if ok && !seen[line] {
				seen[line] = true
				lines = append(lines, line)
			}
		}
	}
	sort.Strings(lines)
	if len(lines) > 0 {
		work += "\n" + replaceMarker + "replace (\n" + strings.Join(lines, "") + ")\n"
	}
	if work == string(raw) {
		return false, nil
	}
	if dryRun {
		return true, nil
	}
	return true, os.WriteFile(workPath, []byte(work), 0o644)
}
